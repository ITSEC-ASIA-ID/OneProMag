/*
   The two reference libraries: how to test an area, and what a finding looks
   like when the test fails.

   Why a module and not a table: this is fixed reference text, not something a
   user creates. A table would mean a schema bump every time a sentence is
   fixed, plus a seed-version dance so a reformatted guide does not overwrite an
   edit nobody can actually make. The checklists are rows because an admin owns
   them; these are read-only pages, so the content ships with the code and the
   route is a two-line read.

   Structure, not prose blobs: the page renders `what` as a paragraph, `steps` as
   a numbered list, and the rest as labelled bullet lists. Nothing parses markup,
   so a guide cannot render as an unreadable wall.

   A guide is keyed to the seeded checklist section it teaches (`A01:2025`,
   `API1:2023`), so the two libraries and the checklist read as one body of
   knowledge rather than three lists that happen to mention OWASP.
*/

